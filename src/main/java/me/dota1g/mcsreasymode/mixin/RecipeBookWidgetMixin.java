package me.dota1g.mcsreasymode.mixin;

import me.dota1g.mcsreasymode.Mcsreasymode;
import net.minecraft.client.MinecraftClient;
import net.minecraft.client.gui.screen.Screen;
import net.minecraft.client.gui.screen.recipebook.RecipeBookWidget;
import net.minecraft.client.gui.widget.TextFieldWidget;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(RecipeBookWidget.class)
public abstract class RecipeBookWidgetMixin {

    @Shadow private TextFieldWidget searchField;

    @Shadow private boolean searching;

    @Inject(method = "keyPressed", at = @At("HEAD"), cancellable = true)
    private void mcsreasymode$focusSearchOnChatKey(int keyCode, int scanCode, int modifiers,
                                                     CallbackInfoReturnable<Boolean> cir) {
        MinecraftClient client = MinecraftClient.getInstance();
        RecipeBookWidget book = (RecipeBookWidget) (Object) this;
        if (!book.isOpen() || searchField == null
                || client.player == null || client.player.isSpectator()
                || !client.options.keyChat.matchesKey(keyCode, scanCode)) {
            return;
        }

        if (!Mcsreasymode.CONFIG.focusSearchOnChatKey) {
            // Vanilla also focuses the search field on the chat key; disable that path for this mode.
            cir.setReturnValue(false);
            return;
        }

        searchField.setSelected(true);
        searching = true; // Suppress the character generated by the chat key itself.
        Screen currentScreen = client.currentScreen;
        if (currentScreen != null) {
            ((AbstractParentElementInvoker) currentScreen).mcsreasymode$setFocused(book);
        }
        cir.setReturnValue(true);
    }

    @Inject(method = "reset", at = @At("TAIL"))
    private void mcsreasymode$autoFocusSearch(boolean isNarrow, CallbackInfo ci) {
        if (searchField == null || !Mcsreasymode.CONFIG.autoFocusSearchField) {
            return;
        }

        searchField.setSelected(true);

        Screen currentScreen = MinecraftClient.getInstance().currentScreen;
        if (currentScreen != null) {
            ((AbstractParentElementInvoker) currentScreen).mcsreasymode$setFocused((RecipeBookWidget) (Object) this);
        }
    }
}
